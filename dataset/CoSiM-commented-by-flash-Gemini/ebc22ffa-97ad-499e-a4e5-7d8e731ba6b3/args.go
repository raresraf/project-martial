/**
 * @file args.go
 * @brief Command-line argument orchestration for automated Go code generation.
 * 
 * This package provides a standardized framework for managing configuration and 
 * execution parameters for code generators (e.g., go2idl). It handles directory 
 * parsing, recursive scanning, and boilerplate management, ensuring consistent 
 * generation behavior across various Kubernetes-aligned tooling.
 * 
 * Domain: Production Systems, Build Infrastructure, Code Generation.
 */

// Package args has common command-line flags for generation programs.
package args

import (
	"bytes"
	"fmt"
	"io/ioutil"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"k8s.io/kubernetes/cmd/libs/go2idl/generator"
	"k8s.io/kubernetes/cmd/libs/go2idl/namer"
	"k8s.io/kubernetes/cmd/libs/go2idl/parser"
	"k8s.io/kubernetes/cmd/libs/go2idl/types"

	"github.com/spf13/pflag"
)

// Default returns a defaulted GeneratorArgs initialized with standard paths.
func Default() *GeneratorArgs {
	generatorArgs := &GeneratorArgs{
		OutputBase:       DefaultSourceTree(),
		GoHeaderFilePath: filepath.Join(DefaultSourceTree(), "k8s.io/kubernetes/hack/boilerplate/boilerplate.go.txt"),
	}
	generatorArgs.AddFlags(pflag.CommandLine)
	return generatorArgs
}

// GeneratorArgs encapsulates the parameters required by Go source code generators.
type GeneratorArgs struct {
	// Which directories to parse for input types.
	InputDirs []string

	// If true, recursive search into InputDirs child directories.
	Recursive bool

	// Absolute path to the source tree for output generation.
	OutputBase string

	// Destination package path for the generated code.
	OutputPackagePath string

	// Path to the file containing license/copyright boilerplate text.
	GoHeaderFilePath string

	// If true, performs validation checks without writing to disk.
	VerifyOnly bool

	// Any custom, generator-specific arguments.
	CustomArgs interface{}
}

// AddFlags binds the generator arguments to a provided pflag.FlagSet for CLI integration.
func (g *GeneratorArgs) AddFlags(fs *pflag.FlagSet) {
	fs.StringSliceVarP(&g.InputDirs, "input-dirs", "i", g.InputDirs, "Comma-separated list of import paths to get input types from.")
	fs.StringVarP(&g.OutputBase, "output-base", "o", g.OutputBase, "Output base; defaults to $GOPATH/src/ or ./ if $GOPATH is not set.")
	fs.StringVarP(&g.OutputPackagePath, "output-package", "p", g.OutputPackagePath, "Base package path.")
	fs.StringVarP(&g.GoHeaderFilePath, "go-header-file", "h", g.GoHeaderFilePath, "File containing boilerplate header text. The string YEAR will be replaced with the current 4-digit year.")
	fs.BoolVar(&g.VerifyOnly, "verify-only", g.VerifyOnly, "If true, only verify existing output, do not write anything.")
	fs.BoolVar(&g.Recursive, "recursive", g.VerifyOnly, "If true, recurse into all children of input directories.")
}

// LoadGoBoilerplate reads the boilerplate file and injects the current year.
func (g *GeneratorArgs) LoadGoBoilerplate() ([]byte, error) {
	b, err := ioutil.ReadFile(g.GoHeaderFilePath)
	if err != nil {
		return nil, err
	}
	// Logic: Template variable replacement for dynamic year stamping.
	b = bytes.Replace(b, []byte("YEAR"), []byte(strconv.Itoa(time.Now().Year())), -1)
	return b, nil
}

// NewBuilder initializes a parser.Builder with the configured input directories.
// It automatically handles recursive vs. flat directory scanning.
func (g *GeneratorArgs) NewBuilder() (*parser.Builder, error) {
	b := parser.New()
	// Build Constraint: Explicitly excludes auto-generated files from the parsing phase.
	b.AddBuildTags("ignore_autogenerated")

	for _, d := range g.InputDirs {
		d = strings.TrimLeft(d, "+-*")
		if g.Recursive {
			if err := b.AddDirRecursive(d); err != nil {
				return nil, fmt.Errorf("unable to add directory %q: %v", d, err)
			}
		} else {
			if err := b.AddDir(d); err != nil {
				return nil, fmt.Errorf("unable to add directory %q: %v", d, err)
			}
		}
	}
	return b, nil
}

// InputIncludes checks if a given package path falls under the configured input scope.
func (g *GeneratorArgs) InputIncludes(p *types.Package) bool {
	for _, dir := range g.InputDirs {
		if strings.HasPrefix(p.Path, dir) {
			return true
		}
	}
	return false
}

// DefaultSourceTree resolves the standard Go source path from $GOPATH environment variables.
func DefaultSourceTree() string {
	paths := strings.Split(os.Getenv("GOPATH"), string(filepath.ListSeparator))
	if len(paths) > 0 && len(paths[0]) > 0 {
		return filepath.Join(paths[0], "src")
	}
	return "./"
}

// Execute orchestrates the full generation workflow: parsing, context creation, and package execution.
func (g *GeneratorArgs) Execute(nameSystems namer.NameSystems, defaultSystem string, pkgs func(*generator.Context, *GeneratorArgs) generator.Packages) error {
	pflag.Parse()

	b, err := g.NewBuilder()
	if err != nil {
		return fmt.Errorf("Failed making a parser: %v", err)
	}

	// Architectural Intent: Abstracts the complexity of type parsing into a generation context.
	c, err := generator.NewContext(b, nameSystems, defaultSystem)
	if err != nil {
		return fmt.Errorf("Failed making a context: %v", err)
	}

	c.Verify = g.VerifyOnly
	packages := pkgs(c, g)
	
	/**
	 * Execution Block: Performs the final code emission phase.
	 * Invariant: packages represents the finalized set of generation instructions.
	 */
	if err := c.ExecutePackages(g.OutputBase, packages); err != nil {
		return fmt.Errorf("Failed executing generator: %v", err)
	}

	return nil
}
